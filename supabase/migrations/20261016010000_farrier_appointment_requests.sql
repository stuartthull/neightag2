-- Public QR submissions are requests only. Calendar writes require owner approval.
DROP FUNCTION IF EXISTS public.add_farrier_calendar_entry(uuid, date, time without time zone, text);

CREATE TABLE public.equi_farrier_appointment_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    horse_uuid uuid NOT NULL REFERENCES public.equi_log_main(horse_uuid) ON DELETE CASCADE,
    appointment_date date NOT NULL,
    appointment_time time without time zone,
    appointment_notes text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    reviewed_at timestamptz,
    reviewed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE INDEX equi_farrier_requests_horse_status_created_idx
    ON public.equi_farrier_appointment_requests (horse_uuid, status, created_at);

ALTER TABLE public.equi_farrier_appointment_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.equi_farrier_appointment_requests FROM anon, authenticated, PUBLIC;
GRANT SELECT ON TABLE public.equi_farrier_appointment_requests TO authenticated;

CREATE POLICY "Owners can view their farrier appointment requests"
    ON public.equi_farrier_appointment_requests
    FOR SELECT
    TO authenticated
    USING (
        EXISTS (
            SELECT 1
            FROM public.equi_log_main AS horse
            WHERE horse.horse_uuid = equi_farrier_appointment_requests.horse_uuid
              AND horse.user_uuid = (SELECT auth.uid())
        )
    );

CREATE OR REPLACE FUNCTION public.submit_farrier_appointment_request(
    target_horse_uuid uuid,
    appointment_date date,
    appointment_time time without time zone DEFAULT NULL,
    appointment_notes text DEFAULT ''
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    new_request_id bigint;
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM public.equi_log_main AS horse
        WHERE horse.horse_uuid = target_horse_uuid
    ) THEN
        RAISE EXCEPTION 'Horse not found';
    END IF;

    IF appointment_date IS NULL OR appointment_date < CURRENT_DATE THEN
        RAISE EXCEPTION 'Appointment date must be today or later';
    END IF;

    IF char_length(COALESCE(appointment_notes, '')) > 2000 THEN
        RAISE EXCEPTION 'Appointment notes must be 2000 characters or fewer';
    END IF;

    INSERT INTO public.equi_farrier_appointment_requests (
        horse_uuid,
        appointment_date,
        appointment_time,
        appointment_notes
    ) VALUES (
        target_horse_uuid,
        appointment_date,
        appointment_time,
        COALESCE(appointment_notes, '')
    )
    RETURNING id INTO new_request_id;

    RETURN new_request_id;
END;
$$;

ALTER FUNCTION public.submit_farrier_appointment_request(uuid, date, time without time zone, text) OWNER TO postgres;
REVOKE ALL ON FUNCTION public.submit_farrier_appointment_request(uuid, date, time without time zone, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.submit_farrier_appointment_request(uuid, date, time without time zone, text) TO anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.review_farrier_appointment_request(
    target_request_id bigint,
    approve_request boolean
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    request_row public.equi_farrier_appointment_requests%ROWTYPE;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Authentication required';
    END IF;

    IF approve_request IS NULL THEN
        RAISE EXCEPTION 'A review decision is required';
    END IF;

    SELECT request.*
    INTO request_row
    FROM public.equi_farrier_appointment_requests AS request
    INNER JOIN public.equi_log_main AS horse
        ON horse.horse_uuid = request.horse_uuid
    WHERE request.id = target_request_id
      AND horse.user_uuid = auth.uid()
    FOR UPDATE OF request;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Request not found or access denied';
    END IF;

    IF request_row.status <> 'pending' THEN
        RAISE EXCEPTION 'This request has already been reviewed';
    END IF;

    IF approve_request THEN
        -- Keep the horse profile's next-visit field in sync with the approved date.
        UPDATE public.equi_log_main
        SET farrier_next_visit = request_row.appointment_date
        WHERE horse_uuid = request_row.horse_uuid
          AND user_uuid = auth.uid();

        INSERT INTO public.equi_calendar (
            user_uuid,
            horse_uuid,
            calendar_date,
            calendar_title,
            calendar_time,
            calendar_notes
        ) VALUES (
            auth.uid(),
            request_row.horse_uuid,
            request_row.appointment_date,
            'Farrier Visit',
            request_row.appointment_time,
            request_row.appointment_notes
        )
        ON CONFLICT (horse_uuid, calendar_title)
        DO UPDATE SET
            calendar_date = EXCLUDED.calendar_date,
            calendar_time = EXCLUDED.calendar_time,
            calendar_notes = EXCLUDED.calendar_notes;
    END IF;

    UPDATE public.equi_farrier_appointment_requests
    SET status = CASE WHEN approve_request THEN 'approved' ELSE 'rejected' END,
        reviewed_at = now(),
        reviewed_by = auth.uid()
    WHERE id = target_request_id;
END;
$$;

ALTER FUNCTION public.review_farrier_appointment_request(bigint, boolean) OWNER TO postgres;
REVOKE ALL ON FUNCTION public.review_farrier_appointment_request(bigint, boolean) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.review_farrier_appointment_request(bigint, boolean) TO authenticated, service_role;
